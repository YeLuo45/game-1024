// Festival skin IDs for auto-detection
export const FESTIVAL_SKINS = ['cny', 'christmas', 'halloween'];

// Get current festival skin based on date
export const getCurrentFestival = () => {
  const now = new Date();
  const month = now.getMonth() + 1; // 1-12
  const date = now.getDate(); // 1-31

  // Check Chinese New Year (simplified: Jan 21 - Feb 20)
  if ((month === 1 && date >= 21) || (month === 2 && date <= 20)) {
    return 'cny';
  }

  // Check Christmas (Dec 20-31)
  if (month === 12 && date >= 20) {
    return 'christmas';
  }

  // Check Halloween (Oct 25-31)
  if (month === 10 && date >= 25) {
    return 'halloween';
  }

  return null;
};

export const getSkin = (skinName) => SKINS[skinName] || SKINS.classic;
